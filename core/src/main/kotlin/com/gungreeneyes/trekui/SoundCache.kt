package com.gungreeneyes.trekui

import android.content.Context
import android.net.Uri
import java.io.File
import java.io.IOException

/**
 * Where a sound id is played from. The production build ships no recordings, so a sound can come
 * from four places, checked in this order:
 *  1. [CACHE]: the clip the user downloaded with DOWNLOAD SOUND LIBRARY, rendered by
 *     [SoundDownloader] into `filesDir/sounds/<id>.wav` (app-private, not backed up);
 *  2. [RAW]: a res/raw resource of the same name (only the owner's personal develop builds
 *     have these, from the gitignored personal_sounds folder);
 *  3. [ASSET]: the launcher's own synthesized clips (`synth_*`, generated by
 *     tools/sounds/synth/make_synth.py, shipped in assets/sounds/synth/ in every build);
 *  4. [NONE]: silence. Callers must treat this as "no sound", never as an error.
 *
 * Imported clips ("lib:" ids) are handled by [SoundLibrary] and never reach this class.
 */
object SoundCache {
    const val NONE = 0
    const val CACHE = 1
    const val RAW = 2
    const val ASSET = 3
    const val DIR = "sounds"
    /** Asset folder of the synthesized set; ids there start with [SYNTH_PREFIX]. */
    const val SYNTH_ASSETS = "sounds/synth/"
    const val SYNTH_PREFIX = "synth_"

    /** Names (without ".ogg") in the synthesized asset folder, read once; guarded by `this`. */
    private var assetNames: MutableSet<String>? = null

    /**
     * The resolution order as a pure function (unit-tested): a downloaded clip wins over a bundled
     * resource, and either wins over silence.
     */
    @JvmStatic
    fun resolve(cached: Boolean, rawResId: Int): Int = resolve(cached, rawResId, false)

    /** As [resolve], with the shipped synthesized asset as the last resort before silence. */
    @JvmStatic
    fun resolve(cached: Boolean, rawResId: Int, asset: Boolean): Int = when {
        cached -> CACHE
        rawResId != 0 -> RAW
        asset -> ASSET
        else -> NONE
    }

    /** The download cache folder; its first use renames clips cached under pre-rename ids ([SoundIdMigration]). */
    @JvmStatic
    fun dir(c: Context): File = File(c.filesDir, DIR).also { SoundIdMigration.migrateCacheOnce(it) }

    /** The cached clip file for an id (it may not exist). Invalid ids map to a name that never exists. */
    @JvmStatic
    fun file(c: Context, id: String?): File =
        File(dir(c), if (SoundCatalog.isValidId(id)) "$id.wav" else "_invalid_.wav")

    @JvmStatic
    fun isCached(c: Context, id: String?): Boolean {
        if (!SoundCatalog.isValidId(id)) return false
        val f = file(c, id)
        return f.isFile && f.length() > 44
    }

    /** Where this id plays from: [CACHE], [RAW], [ASSET] or [NONE]. */
    @JvmStatic
    fun where(c: Context, id: String?): Int {
        if (id == null || id.isEmpty() || "none" == id || id.startsWith(SoundLibrary.PREFIX)) return NONE
        val cached = isCached(c, id)
        val raw = if (cached) 0 else rawId(c, id)
        return resolve(cached, raw, !cached && raw == 0 && hasAsset(c, id))
    }

    /** True if assets/sounds/synth/`id`.ogg exists (the listing is read once). */
    @JvmStatic
    fun hasAsset(c: Context, id: String?): Boolean {
        if (id == null || !id.startsWith(SYNTH_PREFIX)) return false
        return synchronized(this) {
            val names = assetNames ?: HashSet<String>().also { found ->
                assetNames = found
                try {
                    val listed = c.applicationContext.assets.list(SYNTH_ASSETS.substring(0, SYNTH_ASSETS.length - 1))
                    if (listed != null) for (n in listed) if (n.endsWith(".ogg")) found.add(n.substring(0, n.length - 4))
                } catch (ignored: IOException) {
                    // no synthesized set in this build
                }
            }
            names.contains(id)
        }
    }

    /** Asset path of a synthesized clip. */
    @JvmStatic
    fun assetPath(id: String): String = "$SYNTH_ASSETS$id.ogg"

    /** True if the id can be played at all (downloaded, bundled or synthesized). */
    @JvmStatic
    fun available(c: Context, id: String?): Boolean = where(c, id) != NONE

    /**
     * res/raw identifier for the id, or 0 (this lookup is by name: only personal builds have any). A renamed
     * id also finds a clip still named by its old id ([SoundIdMigration.previous]).
     */
    @JvmStatic
    fun rawId(c: Context, id: String?): Int {
        if (!SoundCatalog.isValidId(id)) return 0
        val res = c.resources.getIdentifier(id, "raw", c.packageName)
        val old = if (res == 0) SoundIdMigration.previous(id) else null
        return if (old == null) res else c.resources.getIdentifier(old, "raw", c.packageName)
    }

    /** A playable Uri for MediaPlayer previews: the cached file, the raw resource, or null. */
    @JvmStatic
    fun uri(c: Context, id: String?): Uri? = when (where(c, id)) {
        CACHE -> Uri.fromFile(file(c, id))
        RAW -> Uri.parse("android.resource://" + c.packageName + "/" + rawId(c, id))
        else -> null
    }

    /** Number of downloaded clips. */
    @JvmStatic
    fun count(c: Context): Int = dir(c).listFiles()?.count { it.isFile && it.name.endsWith(".wav") } ?: 0

    /** Total bytes used by downloaded clips. */
    @JvmStatic
    fun bytes(c: Context): Long = dir(c).listFiles()?.filter { it.isFile }?.sumOf { it.length() } ?: 0L

    /** Deletes every downloaded clip (DELETE DOWNLOADED SOUNDS). */
    @JvmStatic
    fun clear(c: Context) {
        SoundImporter.deleteTree(dir(c))
    }
}
