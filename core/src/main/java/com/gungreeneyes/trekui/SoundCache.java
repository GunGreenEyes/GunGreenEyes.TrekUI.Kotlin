package com.gungreeneyes.trekui;

import android.content.Context;
import android.net.Uri;

import java.io.File;

/**
 * Where a sound id is played from. The production build ships no recordings, so a sound can come
 * from four places, checked in this order:
 * <ol>
 *   <li>{@link #CACHE}: the clip the user downloaded with DOWNLOAD SOUND LIBRARY, rendered by
 *       {@link SoundDownloader} into {@code filesDir/sounds/<id>.wav} (app-private, not backed up);</li>
 *   <li>{@link #RAW}: a res/raw resource of the same name (only the owner's personal develop builds
 *       have these, from the gitignored personal_sounds folder);</li>
 *   <li>{@link #ASSET}: the launcher's own synthesized clips ({@code synth_*}, generated by
 *       tools/sounds/synth/make_synth.py, shipped in assets/sounds/synth/ in every build);</li>
 *   <li>{@link #NONE}: silence. Callers must treat this as "no sound", never as an error.</li>
 * </ol>
 * Imported clips ("lib:" ids) are handled by {@link SoundLibrary} and never reach this class.
 */
final class SoundCache {
    static final int NONE = 0, CACHE = 1, RAW = 2, ASSET = 3;
    static final String DIR = "sounds";
    /** Asset folder of the synthesized set; ids there start with {@link #SYNTH_PREFIX}. */
    static final String SYNTH_ASSETS = "sounds/synth/";
    static final String SYNTH_PREFIX = "synth_";

    private SoundCache() {}

    /**
     * The resolution order as a pure function (unit-tested): a downloaded clip wins over a bundled
     * resource, and either wins over silence.
     */
    static int resolve(boolean cached, int rawResId) {
        return resolve(cached, rawResId, false);
    }

    /** As {@link #resolve(boolean, int)}, with the shipped synthesized asset as the last resort before silence. */
    static int resolve(boolean cached, int rawResId, boolean asset) {
        if (cached) return CACHE;
        if (rawResId != 0) return RAW;
        if (asset) return ASSET;
        return NONE;
    }

    static File dir(Context c) { return new File(c.getFilesDir(), DIR); }

    /** The cached clip file for an id (it may not exist). Invalid ids map to a name that never exists. */
    static File file(Context c, String id) {
        return new File(dir(c), SoundCatalog.isValidId(id) ? id + ".wav" : "_invalid_.wav");
    }

    static boolean isCached(Context c, String id) {
        if (!SoundCatalog.isValidId(id)) return false;
        File f = file(c, id);
        return f.isFile() && f.length() > 44;
    }

    /** Where this id plays from: {@link #CACHE}, {@link #RAW} or {@link #NONE}. */
    static int where(Context c, String id) {
        if (id == null || id.isEmpty() || "none".equals(id) || id.startsWith(SoundLibrary.PREFIX)) return NONE;
        boolean cached = isCached(c, id);
        int raw = cached ? 0 : rawId(c, id);
        return resolve(cached, raw, !cached && raw == 0 && hasAsset(c, id));
    }

    private static java.util.Set<String> assetNames;

    /** True if assets/sounds/synth/{@code id}.ogg exists (the listing is read once). */
    static boolean hasAsset(Context c, String id) {
        if (id == null || !id.startsWith(SYNTH_PREFIX)) return false;
        synchronized (SoundCache.class) {
            if (assetNames == null) {
                assetNames = new java.util.HashSet<>();
                try {
                    String[] names = c.getApplicationContext().getAssets().list(SYNTH_ASSETS.substring(0, SYNTH_ASSETS.length() - 1));
                    if (names != null) for (String n : names) if (n.endsWith(".ogg")) assetNames.add(n.substring(0, n.length() - 4));
                } catch (java.io.IOException ignored) {
                    // no synthesized set in this build
                }
            }
            return assetNames.contains(id);
        }
    }

    /** Asset path of a synthesized clip. */
    static String assetPath(String id) { return SYNTH_ASSETS + id + ".ogg"; }

    /** True if the id can be played at all (downloaded or bundled). */
    static boolean available(Context c, String id) { return where(c, id) != NONE; }

    /** res/raw identifier for the id, or 0 (this lookup is by name: only personal builds have any). */
    static int rawId(Context c, String id) {
        if (!SoundCatalog.isValidId(id)) return 0;
        return c.getResources().getIdentifier(id, "raw", c.getPackageName());
    }

    /**
     * A playable Uri for MediaPlayer previews: the cached file, the raw resource, or null.
     */
    static Uri uri(Context c, String id) {
        switch (where(c, id)) {
            case CACHE:
                return Uri.fromFile(file(c, id));
            case RAW:
                return Uri.parse("android.resource://" + c.getPackageName() + "/" + rawId(c, id));
            default:
                return null;
        }
    }

    /** Number of downloaded clips. */
    static int count(Context c) {
        File[] f = dir(c).listFiles();
        int n = 0;
        if (f != null) for (File x : f) if (x.isFile() && x.getName().endsWith(".wav")) n++;
        return n;
    }

    /** Total bytes used by downloaded clips. */
    static long bytes(Context c) {
        File[] f = dir(c).listFiles();
        long n = 0;
        if (f != null) for (File x : f) if (x.isFile()) n += x.length();
        return n;
    }

    /** Deletes every downloaded clip (DELETE DOWNLOADED SOUNDS). */
    static void clear(Context c) {
        SoundImporter.deleteTree(dir(c));
    }
}
